# --- 5. C++-parity fixture test ---------------------------------------------


def test_cpp_parity_fixtures() -> None:
    """Compare against fixtures generated by a MARS C++ (MStarCamTrans) job.

    Skipped if the fixture file has not yet been produced -- it is generated
    by a parallel MARS C++ job and must not be fabricated here. Expected
    fixture schema: a JSON list of records, each with at minimum
    ``dec0_deg``, ``ha0_hours``, ``dec_deg``, ``ha_hours``, ``dist_cam_mm``,
    ``cos_lat``, ``sin_lat``, ``x_mm``, ``y_mm``.
    """
    if not PARITY_FIXTURE_PATH.exists():
        pytest.skip(
            f"C++ parity fixture not found at {PARITY_FIXTURE_PATH}; it is "
            "generated by a MARS C++ job running in parallel and must not "
            "be fabricated here."
        )

    with open(PARITY_FIXTURE_PATH) as handle:
        fixtures = json.load(handle)

    assert fixtures, "Parity fixture file is empty."

    for record in fixtures:
        X, Y = gc.cel0_cel_to_cam(
            record["dec0_deg"],
            record["ha0_hours"],
            record["dec_deg"],
            record["ha_hours"],
            record["dist_cam_mm"],
            record["cos_lat"],
            record["sin_lat"],
        )
        assert X == pytest.approx(record["x_mm"], abs=gc.PARITY_ATOL_MM)
        assert Y == pytest.approx(record["y_mm"], abs=gc.PARITY_ATOL_MM)

        if "theta0_deg" in record and "phi0_deg" in record:
            theta0, phi0 = gc.cel_to_loc(
                record["dec0_deg"],
                record["ha0_hours"],
                record["cos_lat"],
                record["sin_lat"],
            )
            assert theta0 == pytest.approx(
                record["theta0_deg"], abs=gc.PARITY_ATOL_DEG
            )
            assert phi0 == pytest.approx(
                record["phi0_deg"], abs=gc.PARITY_ATOL_DEG
            )


# --- 6. Parity check against the canonical reference module directly -------


@pytest.mark.skipif(
    not _REFERENCE_MODULE_PATH.exists(),
    reason=f"Reference implementation not found at {_REFERENCE_MODULE_PATH}",
)
def test_parity_with_reference_mstarcam_trans() -> None:
    """Outputs match `~/mymars/mstarcam_trans.py` on a random grid, to 1e-12."""
    ref = _load_reference_module()

    rng = np.random.default_rng(42)
    n = 500
    dec0 = rng.uniform(-40.0, 80.0, size=n)
    ha0 = rng.uniform(0.0, 24.0, size=n)
    dec = np.clip(dec0 + rng.uniform(-2.0, 2.0, size=n), -89.0, 89.0)
    ha = gc.wrap24(ha0 + rng.uniform(-0.2, 0.2, size=n))

    # cel_to_loc / loc_to_cel parity
    theta_ref, phi_ref = ref.cel_to_loc(dec, ha, COS_LAT, SIN_LAT)
    theta_new, phi_new = gc.cel_to_loc(dec, ha, COS_LAT, SIN_LAT)
    assert np.allclose(theta_new, theta_ref, atol=1e-12, rtol=1e-12)
    assert np.allclose(phi_new, phi_ref, atol=1e-12, rtol=1e-12)

    dec_ref, ha_ref = ref.loc_to_cel(theta_ref, phi_ref, COS_LAT, SIN_LAT)
    dec_new, ha_new = gc.loc_to_cel(theta_new, phi_new, COS_LAT, SIN_LAT)
    assert np.allclose(dec_new, dec_ref, atol=1e-12, rtol=1e-12)
    assert np.allclose(ha_new, ha_ref, atol=1e-12, rtol=1e-12)

    # cel0_cel_to_cam / cel0_cam_to_cel parity
    X_ref, Y_ref = ref.cel0_cel_to_cam(
        dec0, ha0, dec, ha, DIST_CAM, COS_LAT, SIN_LAT
    )
    X_new, Y_new = gc.cel0_cel_to_cam(
        dec0, ha0, dec, ha, DIST_CAM, COS_LAT, SIN_LAT
    )
    assert np.allclose(X_new, X_ref, atol=1e-12, rtol=1e-12)
    assert np.allclose(Y_new, Y_ref, atol=1e-12, rtol=1e-12)

    dec2_ref, ha2_ref = ref.cel0_cam_to_cel(
        dec0, ha0, X_ref, Y_ref, DIST_CAM, COS_LAT, SIN_LAT
    )
    dec2_new, ha2_new = gc.cel0_cam_to_cel(
        dec0, ha0, X_new, Y_new, DIST_CAM, COS_LAT, SIN_LAT
    )
    assert np.allclose(dec2_new, dec2_ref, atol=1e-12, rtol=1e-12)
    assert np.allclose(ha2_new, ha2_ref, atol=1e-12, rtol=1e-12)

    # loc0_loc_to_cam / loc0_cam_to_loc parity (independent local-only grid)
    theta0 = rng.uniform(1.0, 89.0, size=n)
    phi0 = rng.uniform(0.0, 360.0, size=n)
    theta = np.clip(theta0 + rng.uniform(-5.0, 5.0, size=n), 0.5, 89.5)
    phi = phi0 + rng.uniform(-5.0, 5.0, size=n)

    X3_ref, Y3_ref = ref.loc0_loc_to_cam(theta0, phi0, theta, phi, DIST_CAM)
    X3_new, Y3_new = gc.loc0_loc_to_cam(theta0, phi0, theta, phi, DIST_CAM)
    assert np.allclose(X3_new, X3_ref, atol=1e-12, rtol=1e-12)
    assert np.allclose(Y3_new, Y3_ref, atol=1e-12, rtol=1e-12)

    theta_b_ref, phi_b_ref = ref.loc0_cam_to_loc(
        theta0, phi0, X3_ref, Y3_ref, DIST_CAM
    )
    theta_b_new, phi_b_new = gc.loc0_cam_to_loc(
        theta0, phi0, X3_new, Y3_new, DIST_CAM
    )
    assert np.allclose(theta_b_new, theta_b_ref, atol=1e-12, rtol=1e-12)
    assert np.allclose(phi_b_new, phi_b_ref, atol=1e-12, rtol=1e-12)
