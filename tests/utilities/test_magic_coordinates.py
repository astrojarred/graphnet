# --- Angular separation correctness ----------------------------------------


def test_angular_separation_deg_known_values() -> None:
    """Sanity-check `angular_separation_deg` against known geometric cases."""
    # Same point -> zero separation.
    assert gc.angular_separation_deg(10.0, 20.0, 10.0, 20.0) == pytest.approx(
        0.0, abs=1e-9
    )

    # Separation along a declination-only offset (great-circle == delta dec).
    sep = gc.angular_separation_deg(10.0, 0.0, 10.0, 1.0)
    assert sep == pytest.approx(1.0, abs=1e-9)

    # Antipodal points on the sphere (ra offset 180 deg, dec negated) -> 180 deg.
    sep = gc.angular_separation_deg(0.0, 30.0, 180.0, -30.0)
    assert sep == pytest.approx(180.0, abs=1e-6)

    # RA in hours must match RA in degrees scaled by 15.
    sep_deg = gc.angular_separation_deg(30.0, 10.0, 45.0, 12.0, ra_unit="deg")
    sep_hours = gc.angular_separation_deg(
        2.0, 10.0, 3.0, 12.0, ra_unit="hours"
    )
    assert sep_deg == pytest.approx(sep_hours, abs=1e-9)


