_REFERENCE_MODULE_PATH = Path("~/mymars/mstarcam_trans.py").expanduser()


def _load_reference_module():
    """Load the canonical reference implementation as a standalone module."""
    spec = importlib.util.spec_from_file_location(
        "mstarcam_trans_reference", _REFERENCE_MODULE_PATH
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _ha_wrap_diff(a: float, b: float) -> float:
    diff = abs(a - b)
    return min(diff, 24.0 - diff)


def _az_wrap_diff(a: float, b: float) -> float:
    diff = abs(a - b)
    return min(diff, 360.0 - diff)


