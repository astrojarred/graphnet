def test_scalar_vs_vector_all_public_transforms() -> None:
    """All main transforms give identical scalar and length-1-array results."""
    dec0, ha0 = 22.0, 1.5
    theta0, phi0 = 30.0, 180.0
    X, Y = 123.4, -56.7
    dec, ha = 24.1, 2.0
