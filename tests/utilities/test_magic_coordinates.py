# --- 2. Round-trip tests over randomized grids, including wrap boundaries -


@pytest.mark.parametrize("seed", [0, 1, 2])
def test_loc0_roundtrip_random_grid(seed: int) -> None:
    """`loc0_loc_to_cam` <-> `loc0_cam_to_loc` over a random grid."""
    rng = np.random.default_rng(seed)
    n = 200
    theta0 = rng.uniform(1.0, 89.0, size=n)
    phi0 = rng.uniform(0.0, 360.0, size=n)
    dtheta = rng.uniform(-5.0, 5.0, size=n)
    dphi = rng.uniform(-5.0, 5.0, size=n)
    theta = np.clip(theta0 + dtheta, 0.5, 89.5)
    phi = phi0 + dphi

    X, Y = gc.loc0_loc_to_cam(theta0, phi0, theta, phi, DIST_CAM)
    theta_back, phi_back = gc.loc0_cam_to_loc(theta0, phi0, X, Y, DIST_CAM)

    assert np.allclose(theta_back, theta, rtol=RTOL, atol=ATOL)
    phi_diff = np.minimum(
        np.abs(phi_back - phi) % 360.0, 360.0 - np.abs(phi_back - phi) % 360.0
    )
    assert np.allclose(phi_diff, 0.0, atol=1e-3)


@pytest.mark.parametrize("seed", [0, 1, 2])
def test_cel0_roundtrip_random_grid(seed: int) -> None:
    """`cel0_cel_to_cam` <-> `cel0_cam_to_cel` over a random grid."""
    rng = np.random.default_rng(seed + 100)
    n = 200
    dec0 = rng.uniform(-40.0, 80.0, size=n)
    ha0 = rng.uniform(0.0, 24.0, size=n)
    dec = np.clip(dec0 + rng.uniform(-2.0, 2.0, size=n), -89.0, 89.0)
    ha = ha0 + rng.uniform(-0.2, 0.2, size=n)

    X, Y = gc.cel0_cel_to_cam(dec0, ha0, dec, ha, DIST_CAM, COS_LAT, SIN_LAT)
    dec_back, ha_back = gc.cel0_cam_to_cel(
        dec0, ha0, X, Y, DIST_CAM, COS_LAT, SIN_LAT
    )

    assert np.allclose(dec_back, dec, rtol=RTOL, atol=ATOL)
    ha_diff = np.minimum(
        np.abs(ha_back - ha % 24.0), 24.0 - np.abs(ha_back - ha % 24.0)
    )
    assert np.allclose(ha_diff, 0.0, atol=ATOL)


@pytest.mark.parametrize("seed", [0, 1, 2])
def test_cel_loc_roundtrip_random_grid_with_wrap(seed: int) -> None:
    """`cel_to_loc` <-> `loc_to_cel` over a grid spanning HA wrap boundaries."""
    rng = np.random.default_rng(seed + 200)
    n = 200
    dec = rng.uniform(-85.0, 85.0, size=n)
    # Include values that straddle the [0, 24) wrap boundary explicitly.
    ha = np.concatenate(
        [
            rng.uniform(0.0, 24.0, size=n - 4),
            np.array([-0.001, 0.0, 23.999, 24.0]),
        ]
    )
    dec = np.concatenate([dec[: n - 4], np.array([22.0, 22.0, 22.0, 22.0])])

    theta, phi = gc.cel_to_loc(dec, ha, COS_LAT, SIN_LAT)
    dec_back, ha_back = gc.loc_to_cel(theta, phi, COS_LAT, SIN_LAT)

    assert np.allclose(dec_back, dec, rtol=RTOL, atol=ATOL)
    ha_wrapped = gc.wrap24(ha)
    ha_diff = np.minimum(
        np.abs(ha_back - ha_wrapped), 24.0 - np.abs(ha_back - ha_wrapped)
    )
    assert np.allclose(ha_diff, 0.0, atol=ATOL)


